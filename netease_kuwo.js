function extractJsonStr(json,key){
  const idx=json.indexOf(key);
  if(idx<0)return null;
  const start=idx+key.length;
  const end=json.indexOf('"',start);
  if(end<0)return null;
  return json.substring(start,end).replace(/\\"/g,'"');
}
